        predatorAssimilationFraction = FiniteClamp(predatorAssimilationFraction, fallback.predatorAssimilationFraction, 0f, 1f);
        hydrogenTempRange = NormalizeRange(hydrogenTempRange, fallback.hydrogenTempRange);
        sulfurChemoTempRange = NormalizeRange(sulfurChemoTempRange, fallback.sulfurChemoTempRange);
        photoTempRange = NormalizeRange(photoTempRange, fallback.photoTempRange);
        saproTempRange = NormalizeRange(saproTempRange, fallback.saproTempRange);
        predatorTempRange = NormalizeRange(predatorTempRange, fallback.predatorTempRange);
        fermentationTempRange = NormalizeRange(fermentationTempRange, fallback.fermentationTempRange);
        methanogenesisTempRange = NormalizeRange(methanogenesisTempRange, fallback.methanogenesisTempRange);
        methanotrophyTempRange = NormalizeRange(methanotrophyTempRange, fallback.methanotrophyTempRange);
        defaultLethalMargin = FiniteClamp(defaultLethalMargin, fallback.defaultLethalMargin, 1f, float.MaxValue);
        temperatureDormancyFloor = FiniteClamp(temperatureDormancyFloor, fallback.temperatureDormancyFloor, 0f, 1f);
        temperatureReplicationMinEfficiency = FiniteClamp(temperatureReplicationMinEfficiency, fallback.temperatureReplicationMinEfficiency, 0f, 1f);
        tempMutationChance = FiniteClamp(tempMutationChance, fallback.tempMutationChance, 0f, 1f);
        tempMutationScale = float.IsFinite(tempMutationScale) ? Mathf.Abs(tempMutationScale) : fallback.tempMutationScale;
        extremeColdDeathTempKelvin = FiniteClamp(extremeColdDeathTempKelvin, fallback.extremeColdDeathTempKelvin, 0f, float.MaxValue);
        extremeHeatDeathTempKelvin = FiniteClamp(extremeHeatDeathTempKelvin, fallback.extremeHeatDeathTempKelvin, 0f, float.MaxValue);
        geodesicTemperatureStressMaintenanceMultiplier = FiniteClamp(geodesicTemperatureStressMaintenanceMultiplier, fallback.geodesicTemperatureStressMaintenanceMultiplier, 0f, float.MaxValue);
        geodesicColdExposureDeathSeconds = FiniteClamp(geodesicColdExposureDeathSeconds, fallback.geodesicColdExposureDeathSeconds, 0f, float.MaxValue);
        geodesicHeatExposureDeathSeconds = FiniteClamp(geodesicHeatExposureDeathSeconds, fallback.geodesicHeatExposureDeathSeconds, 0f, float.MaxValue);
        geodesicTemperatureExposureRecoveryPerSecond = FiniteClamp(geodesicTemperatureExposureRecoveryPerSecond, fallback.geodesicTemperatureExposureRecoveryPerSecond, 0f, float.MaxValue);
        geodesicAmoeboidEnergyPerSecond = FiniteClamp(geodesicAmoeboidEnergyPerSecond, fallback.geodesicAmoeboidEnergyPerSecond, 0f, 1000f);
        geodesicFlagellumEnergyPerSecond = FiniteClamp(geodesicFlagellumEnergyPerSecond, fallback.geodesicFlagellumEnergyPerSecond, 0f, 1000f);
        if (extremeColdDeathTempKelvin > extremeHeatDeathTempKelvin)
            (extremeColdDeathTempKelvin, extremeHeatDeathTempKelvin) = (extremeHeatDeathTempKelvin, extremeColdDeathTempKelvin);
    }

    private static float FiniteClamp(float value, float fallback, float min, float max) =>
        float.IsFinite(value) ? Mathf.Clamp(value, min, max) : fallback;

    internal static Vector2 NormalizeRange(Vector2 range, Vector2 fallback)
    {
        if (!float.IsFinite(range.x) || !float.IsFinite(range.y)) return fallback;
        float min = Mathf.Clamp(Mathf.Min(range.x, range.y), 150f, 500f);
        float max = Mathf.Clamp(Mathf.Max(range.x, range.y), 150f, 500f);
        return new Vector2(min, max);
    }
